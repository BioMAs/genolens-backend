def test_the_generated_keys_are_the_ones_the_application_loads(monkeypatch, clean_key_caches):
    """The written values go through the application's own loaders: a key the template wrote that
    the API could not read would be found out on the first sign-in, in production."""
    values = build()
    monkeypatch.setattr(settings, "AUTH_JWT_PRIVATE_KEYS", values["AUTH_JWT_PRIVATE_KEYS"])
    monkeypatch.setattr(settings, "AUTH_ENCRYPTION_KEYS", values["AUTH_ENCRYPTION_KEYS"])
    assert len(load_signing_keys()) == 1
    ciphertext = load_cipher().encrypt(b"seed")
    assert load_cipher().decrypt(ciphertext) == b"seed"


def test_the_written_values_survive_a_dotenv_read():
    """A base64 key ends with `=` and holds `+` and `/`: none of it may need quoting."""
    content = _build_backend_env(BASE_ENV, SERVER)
    for line in content.splitlines():
        if line.startswith(("AUTH_JWT_PRIVATE_KEYS=", "AUTH_ENCRYPTION_KEYS=")):
            value = line.partition("=")[2]
            assert not re.search(r"[\s'\"#$\\]", value)


def test_the_expected_secrets_name_the_auth_settings_and_not_the_hosted_provider():
    keys = SERVICE_ENV_KEYS["backend"]
