class FakeSftp:
    def __init__(self, written):
        self.written = written

    def open(self, path, mode):
        written = self.written

        class File:
            def __enter__(self_inner):
                return self_inner

            def __exit__(self_inner, *exc):
                return False

            def write(self_inner, content):
                written[path] = content

        return File()

    def close(self):
        pass


@pytest.fixture
def ssh(monkeypatch):
    """A fake SSH layer: every remote command succeeds, the files written are recorded in `.files`
    and the lines the task logs in `.lines` (the log is read here, not through SQLite, whose UUID
    storage differs from the raw SQL the log append uses)."""
    remote = SimpleNamespace(files={}, lines=[])

    class FakeClient:
        def set_missing_host_key_policy(self, *_):
            pass

        def connect(self, **_):
            pass

        def get_transport(self):
            return SimpleNamespace(open_session=lambda: SimpleNamespace(close=lambda: None))

        def open_sftp(self):
            return FakeSftp(remote.files)

        def close(self):
            pass

    async def no_sleep(_):
        return None

    async def record(_db, _job_id, line):
        remote.lines.append(line)

    monkeypatch.setattr(deployment_task.paramiko, "SSHClient", FakeClient)
    monkeypatch.setattr(deployment_task, "_run_ssh_command", lambda *_args, **_kw: ("", 0))
    monkeypatch.setattr(deployment_task, "_append_log", record)
    monkeypatch.setattr(deployment_task.asyncio, "sleep", no_sleep)
    return remote


def new_job(sessions, server, services):
    async def create():
        async with sessions() as db:
            job = DeploymentJob(
                id=uuid4(), server_id=server.id, services=list(services), skip_build=True
            )
            db.add(job)
            await db.commit()
            return job.id

    return asyncio.run(create())


def read_job(sessions, job_id) -> DeploymentJob:
    async def read():
        async with sessions() as db:
            return (
                await db.execute(select(DeploymentJob).where(DeploymentJob.id == job_id))
            ).scalar_one()

    return asyncio.run(read())


def deploy(sessions, server, services=("backend",)) -> None:
    job_id = new_job(sessions, server, services)
    result = deployment_task.run_deployment.run(job_id)
    assert result == {"status": "success"}, result
    assert read_job(sessions, job_id).status == DeploymentStatus.SUCCESS


ENV_PATH = "/opt/genolens/backend/.env"


def test_the_task_keeps_the_same_keys_across_deploys(sessions, encryption_key, ssh, monkeypatch):
    monkeypatch.setattr(deployment_task, "AsyncSessionLocal", sessions)
    server = seed_server(sessions, dict(BASE_ENV))

    deploy(sessions, server)
    first = parse(ssh.files[ENV_PATH])
    first_log = "\n".join(ssh.lines)
    assert first["AUTH_MODE"] == "local"
    assert "SUPABASE_" not in ssh.files[ENV_PATH]
    assert first["AUTH_ISSUER"] == "https://api.onprem.example.test"
    assert stored(sessions, server.id)["AUTH_JWT_PRIVATE_KEYS"] == first["AUTH_JWT_PRIVATE_KEYS"]
    assert stored(sessions, server.id)["AUTH_ENCRYPTION_KEYS"] == first["AUTH_ENCRYPTION_KEYS"]
    assert "AUTH_JWT_PRIVATE_KEYS" in first_log and "AUTH_ENCRYPTION_KEYS" in first_log  # named...
    assert first["AUTH_JWT_PRIVATE_KEYS"] not in first_log  # ...never their value
    assert first["AUTH_ENCRYPTION_KEYS"] not in first_log

    ssh.files.clear()
    ssh.lines.clear()
    deploy(sessions, server)
    second = parse(ssh.files[ENV_PATH])
    assert second["AUTH_JWT_PRIVATE_KEYS"] == first["AUTH_JWT_PRIVATE_KEYS"]
    assert second["AUTH_ENCRYPTION_KEYS"] == first["AUTH_ENCRYPTION_KEYS"]
    assert "generated" not in "\n".join(ssh.lines)


def test_a_deploy_without_the_backend_does_not_mint_keys(
    sessions, encryption_key, ssh, monkeypatch
):
    monkeypatch.setattr(deployment_task, "AsyncSessionLocal", sessions)
    server = seed_server(sessions, dict(BASE_ENV))
    deploy(sessions, server, services=("license",))
    assert not [key for key in stored(sessions, server.id) if key.startswith("AUTH_")]
    assert ENV_PATH not in ssh.files


def test_the_task_fails_cleanly_when_the_keys_cannot_be_stored(
    sessions, encryption_key, ssh, monkeypatch
):
    """No `.env` is written with keys that were not kept: the job fails and says why."""
    monkeypatch.setattr(deployment_task, "AsyncSessionLocal", sessions)
    server = seed_server(sessions, dict(BASE_ENV))

    async def refuse(*_args, **_kw):
        raise RuntimeError("database unavailable")

    monkeypatch.setattr(deployment_task, "ensure_auth_secrets", refuse)
    job_id = new_job(sessions, server, ["backend"])

    assert deployment_task.run_deployment.run(job_id) == {"status": "error"}
    assert ENV_PATH not in ssh.files
    job = read_job(sessions, job_id)
    assert job.status == DeploymentStatus.FAILED
    assert "authentication keys" in (job.logs or "")
