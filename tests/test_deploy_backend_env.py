"""
The `.env` the admin deploy task writes on an on-premise server runs its own authentication.

An on-premise instance has no hosted identity provider: `_build_backend_env` writes
`AUTH_MODE=local` and the instance's own keys instead of the `SUPABASE_*` settings. The two keys
(`AUTH_JWT_PRIVATE_KEYS`, `AUTH_ENCRYPTION_KEYS`) are generated per instance and then KEPT: a new
signing key signs every user out, a new encryption key makes every second-factor secret
unreadable, so a deploy that regenerated them would be an outage. They are stored with the
server's other secrets (`deployment_secrets`, encrypted like the rest) the first time they are
generated, and read back at every later deploy.

Everything here is fictitious: the keys are generated by the test, the hosts are `.example.test`.
"""

