    env_vars = stored(sessions, server.id)
    assert run_ensure(sessions, server.id, env_vars) == []
    assert stored(sessions, server.id) == {
        "AUTH_JWT_PRIVATE_KEYS": signing,
        "AUTH_ENCRYPTION_KEYS": encryption,
    }


