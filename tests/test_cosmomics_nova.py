def test_sector_order_is_s_pro_descending(reference):
    fx, nova = reference
    names = [c["name"] for c in nova["claims"]]
    assert names == ["Regeneration", "Firming", "Barrier", "Anti-ageing", "Soothing", "Antioxidant"]
    assert names == [c["name"] for c in fx["claims"]]


def test_every_claim_value_matches_the_fixture(reference):
    fx, nova = reference
    got = {c["name"]: c for c in nova["claims"]}
    for want in fx["claims"]:
        claim = got[want["name"]]
        for key in ("importance", "s_pro", "s_anti", "coherence", "best_nl"):
            assert claim[key] == pytest.approx(want[key], abs=TOL), (want["name"], key)
        assert (claim["n_for"], claim["n_against"]) == (want["n_for"], want["n_against"])
        assert claim["best_subgroup"] == want["best_subgroup"]

        subs = {s["name"]: s for s in claim["subgroups"]}
        assert set(subs) == {s["name"] for s in want["subgroups"]}
        for want_sub in want["subgroups"]:
            sub = subs[want_sub["name"]]
            for key in ("nl", "s_pro", "s_anti", "delta", "balance"):
                assert sub[key] == pytest.approx(want_sub[key], abs=TOL), (want_sub["name"], key)
            assert sub["obs"] == want_sub["obs"]
            terms = {t["id"]: t for t in sub["terms"]}
            for want_term in want_sub["terms"]:
                term = terms[want_term["id"]]
                assert term["nl"] == pytest.approx(want_term["nl"], abs=TOL)
                assert (term["effect"], term["obs"]) == (want_term["effect"], want_term["obs"])


def test_unlinked_matches_the_fixture(reference):
    fx, nova = reference
    got = {s["name"]: s for s in nova["unlinked"]}
    assert set(got) == {s["name"] for s in fx["unlinked"]}
    for want in fx["unlinked"]:
        assert got[want["name"]]["nl"] == pytest.approx(want["nl"], abs=TOL)
        assert all(t["effect"] == 0 for t in got[want["name"]]["terms"])
    assert nova["unlinked_total"] == len(fx["unlinked"])


def test_reference_headline_values(reference):
    _, nova = reference
    claims = {c["name"]: c for c in nova["claims"]}

    regeneration = claims["Regeneration"]
    assert max(nova["claims"], key=lambda c: c["importance"])["name"] == "Regeneration"
    assert regeneration["importance"] == pytest.approx(68.3, abs=TOL)
    assert (regeneration["n_for"], regeneration["n_against"]) == (7, 1)

    assert (claims["Firming"]["n_for"], claims["Firming"]["n_against"]) == (5, 0)

    antioxidant = claims["Antioxidant"]
    assert antioxidant["n_against"] == 1
    against = [s["name"] for s in antioxidant["subgroups"] if s["delta"] <= 0]
    assert against == ["Mitochondrial respiration"]


def test_one_pathway_can_serve_two_claims_independently(reference):
    """GO:0006914 (Autophagy) sits in Anti-ageing and in Regeneration; neither absorbs it."""
    _, nova = reference
    owners = [
        c["name"]
        for c in nova["claims"]
        for s in c["subgroups"]
        if any(t["id"] == "GO:0006914" for t in s["terms"])
    ]
    assert sorted(owners) == ["Anti-ageing", "Regeneration"]


