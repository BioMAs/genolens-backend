def test_msigdb_names_match_by_label_but_accessions_do_not():
    rows = [
        SubgroupTerm(
            "Firming",
            "Collagen",
            "HSA-1650814",
            "Collagen biosynthesis and modifying enzymes",
            "up",
        )
    ]
    mapping = ClaimSubgroupMap(rows)
    msigdb = TermHit(
        "REACTOME_COLLAGEN_BIOSYNTHESIS_AND_MODIFYING_ENZYMES",
        "REACTOME_COLLAGEN_BIOSYNTHESIS_AND_MODIFYING_ENZYMES",
        1e-4,
        "up",
    )
    homonym = TermHit("GO:9999999", "Collagen biosynthesis and modifying enzymes", 1e-4, "up")
    assert mapping.lookup(msigdb) == rows
    assert mapping.lookup(homonym) == []
    nova = build_nova([msigdb], mapping)
    assert nova["claims"][0]["subgroups"][0]["terms"][0]["id"] == "R-HSA-1650814"


