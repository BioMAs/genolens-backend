FIXTURE = Path(__file__).parent / "fixtures" / "cosmomics_nova_mock.json"
TOL = 1e-3


def _opposite(direction: str) -> str:
    return "down" if direction == "up" else "up"


def _fixture_inputs() -> tuple[dict, ClaimSubgroupMap, list[TermHit]]:
    """Referential and enrichment hits that the reference script turned into the fixture."""
    fx = json.loads(FIXTURE.read_text(encoding="utf-8"))
    rows: list[SubgroupTerm] = []
    hits: dict[tuple[str, str], TermHit] = {}
    for claim in fx["claims"]:
        for sub in claim["subgroups"]:
            for t in sub["terms"]:
                expected = t["obs"] if t["effect"] == 1 else _opposite(t["obs"])
                rows.append(SubgroupTerm(claim["name"], sub["name"], t["id"], t["label"], expected))
                hits[(t["id"], t["obs"])] = TermHit(t["id"], t["label"], 10 ** -t["nl"], t["obs"])
    for sub in fx["unlinked"]:
        for t in sub["terms"]:
            rows.append(SubgroupTerm(None, sub["name"], t["id"], t["label"], None))
            hits[(t["id"], t["obs"])] = TermHit(t["id"], t["label"], 10 ** -t["nl"], t["obs"])
    return fx, ClaimSubgroupMap(rows), list(hits.values())


