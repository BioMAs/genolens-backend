# ── Stouffer ────────────────────────────────────────────────────────────────


@pytest.mark.parametrize(
    "ps",
    [[0.05], [0.01, 0.2], [1e-200], [1e-200, 0.5, 0.9], [0.3, 0.3, 0.3, 0.3]],
    ids=["single", "pair", "1e-200", "extreme-mixed", "four-weak"],
)
def test_stouffer_matches_scipy(ps):
    expected = norm.sf(sum(norm.isf(p) for p in ps) / math.sqrt(len(ps)))
    assert stouffer_p(ps) == pytest.approx(expected, rel=1e-9)


def test_stouffer_single_term_is_identity_even_at_1e_200():
    assert stouffer_p([1e-200]) == pytest.approx(1e-200, rel=1e-6)


def test_stouffer_is_bounded_at_1e_300():
    # Four terms at the floor combine far below double precision: bounded, not 0.
    assert stouffer_p([1e-300] * 4) == P_FLOOR
    assert stouffer_p([0.0]) == P_FLOOR


def test_stouffer_padj_of_one_is_no_evidence():
    assert stouffer_p([1.0]) == pytest.approx(1.0, abs=1e-9)


