def test_unmapped_significant_terms_are_not_linked_with_null_effect():
    hits = [
        TermHit("GO:0008380", "RNA splicing (GO:0008380)", 1e-4, "down"),
        TermHit("GO:0000398", "mRNA splicing, via spliceosome (GO:0000398)", 1e-3, "down"),
        TermHit("GO:0000002", "Something faint (GO:0000002)", 0.2, "up"),
    ]
    nova = build_nova(hits, ClaimSubgroupMap([]))
    assert nova["claims"] == []
    assert [s["name"] for s in nova["unlinked"]] == ["RNA splicing"]
    assert {t["effect"] for t in nova["unlinked"][0]["terms"]} == {0}
    assert nova["unlinked_total"] == 1  # the faint sub-group is not significant


def test_unlinked_is_capped_but_counted():
    hits = [TermHit(f"GO:{i:07d}", f"Pathway number {i}", 1e-3, "up") for i in range(10)]
    nova = build_nova(hits, ClaimSubgroupMap([]), unlinked_limit=4)
