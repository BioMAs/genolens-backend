def _one_claim(*terms: tuple[str, float, str, str]) -> dict:
    """terms: (term_id, p, observed, expected) in a single sub-group of claim Firming."""
    rows = [SubgroupTerm("Firming", "Collagen", tid, tid, exp) for tid, _, _, exp in terms]
    hits = [TermHit(tid, tid, p, obs) for tid, p, obs, _ in terms]
    return build_nova(hits, ClaimSubgroupMap(rows))


def test_no_anti_term_gives_balance_one_and_full_coherence():
    nova = _one_claim(("GO:0000001", 1e-4, "up", "up"), ("GO:0000002", 1e-3, "up", "up"))
    claim = nova["claims"][0]
    sub = claim["subgroups"][0]
    assert sub["s_anti"] == 0
    assert sub["balance"] == 1.0
    assert claim["coherence"] == 1.0
    assert (claim["n_for"], claim["n_against"]) == (1, 0)


def test_no_pro_term_gives_balance_minus_one_and_zero_coherence():
    nova = _one_claim(("GO:0000001", 1e-4, "down", "up"))
    claim = nova["claims"][0]
    assert claim["subgroups"][0]["balance"] == -1.0
    assert claim["coherence"] == 0.0
    assert (claim["n_for"], claim["n_against"]) == (0, 1)


def test_balanced_sub_group_counts_against():
    """delta == 0 is "against" (n_against counts delta <= 0), balance and delta are 0."""
    nova = _one_claim(("GO:0000001", 1e-3, "up", "up"), ("GO:0000002", 1e-3, "down", "up"))
    claim = nova["claims"][0]
    sub = claim["subgroups"][0]
    assert sub["delta"] == pytest.approx(0.0)
    assert sub["balance"] == pytest.approx(0.0)
    assert claim["coherence"] == pytest.approx(0.5)
    assert (claim["n_for"], claim["n_against"]) == (0, 1)


